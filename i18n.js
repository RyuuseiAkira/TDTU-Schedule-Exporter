function tr(source) { return SETTINGS.language === 'vi' ? source : (UI_EN[source] ?? source); }
function applyLanguage(language) {
  SETTINGS.language = language === 'vi' ? 'vi' : 'en';
  if (typeof document === 'undefined') return;
  document.documentElement.lang = SETTINGS.language;
  document.body.classList.toggle('motion-off', SETTINGS.animateMascot === false);
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = tr(el.dataset.i18n); });
  for (const attr of ['aria-label', 'title', 'placeholder']) {
    document.querySelectorAll('[data-i18n-' + attr + ']').forEach(el => {
      el.setAttribute(attr, tr(el.getAttribute('data-i18n-' + attr)));
    });
  }
}
if (typeof document !== 'undefined') applyLanguage('en');

function classCount(count) {
  return SETTINGS.language === 'vi' ? count + ' lớp học' : count + (count === 1 ? ' class' : ' classes');
}
